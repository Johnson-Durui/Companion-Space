import { existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("../", import.meta.url));
const target = new URL("../packages/api-client/schema.d.ts", import.meta.url);
const localPython = fileURLToPath(new URL(process.platform === "win32" ? "../.venv/Scripts/python.exe" : "../.venv/bin/python", import.meta.url));
const python = process.env.COMPANION_PYTHON || (existsSync(localPython) ? localPython : "python");
const schema = spawnSync(python, ["-c", "import json; from app.main import app; print(json.dumps(app.openapi(), sort_keys=True))"], {
  cwd: root,
  env: { ...process.env, PYTHONPATH: "services/api", PYTHONIOENCODING: "utf-8" },
  encoding: "utf8",
});
if (schema.error || schema.status !== 0) {
  throw new Error("Could not generate the FastAPI contract", { cause: schema.error ?? schema.stderr });
}
const generated = "// Generated by npm run generate:api.\n" + astToString(await openapiTS(JSON.parse(schema.stdout)));
if (process.argv.includes("--check")) {
  if (generated !== (await readFile(target, "utf8")).replaceAll("\r\n", "\n")) throw new Error("OpenAPI contract is stale. Run npm run generate:api.");
} else {
  await writeFile(target, generated);
}
